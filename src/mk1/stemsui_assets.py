#!/usr/bin/env python3
"""STEMS pad artwork for the MK1 PERFORM BEAT JUMP row (RGB565, for stemsui.c).

Source: the stock PERFORM screenshot (model table stemsui_layout.source).
Per pad: the stock pixels of that BEAT JUMP pad with the tab's << / >> arrows
filled with the tab colour and the digit band rebuilt from the pad's own
texture (rows repeat with a period <= 4 px, see bjlabels.py), then our text
in Helvetica Neue Bold (as ksui_assets.py): white = stem ON, dim = MUTED.

Images (packed into stemsui_img.bin; offsets in stemsui_layout.h):
  ON0..ON3 / MU0..MU3   VOCALS DRUMS BASS OTHER, on / muted (pads 1..4)
  ALL                   ALL ON (pad 5)        BACK  BACK (pad 6)
  TITLE                 "STEMS" over the row label, label colour (view open)
  ALERT                 "STEMS" in red (view closed, a stem muted)

    stemsui_assets.py build   -> work/stemsui/build/stemsui_img.bin, stemsui_layout.h, preview.png
"""
import hashlib
import json
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import ksui_assets as K                                        # noqa: E402

E_ = json.load(open(os.path.join(HERE, "models", "xdj1000_113.json")))["entries"]
L = E_["stemsui_layout"]
PADS = {int(k): tuple(v) for k, v in E_["bj_pad_rects"]["x"].items()}
OUT = os.path.join(ROOT, "work", "stemsui", "build")
NAMES = ("VOCALS", "DRUMS", "BASS", "OTHER")


def clear_tab(p, rows):
    """fill the arrow pixels inside the pad's tab with the tab colour, row by row:
    in rows where the bright part is only the tab (narrower than 60% of the pad),
    every pixel between its first and last bright pixel becomes the row's tab colour"""
    out = p.copy()
    W = p.shape[1]
    lum = p.sum(axis=2)
    for y in rows:
        br = np.nonzero(lum[y] > lum[y].max() * 0.75)[0]
        if len(br) < 3 or br[-1] - br[0] > 0.6 * W:
            continue
        vals, cnt = np.unique(p[y, br].reshape(-1, 3), axis=0, return_counts=True)
        out[y, br[0]:br[-1] + 1] = vals[cnt.argmax()]
    return out


def build():
    scr = K.to565(np.asarray(Image.open(os.path.join(ROOT, L["source"])).convert("RGB")))
    y0, y1 = L["row_y"]
    H = y1 - y0 + 1
    hdr = range(L["header_rows"][0] - y0, L["header_rows"][1] - y0 + 1)
    band = range(L["text_band"][0] - y0, L["text_band"][1] - y0 + 1)
    font = K.font_for(L["cap"])
    base = L["baseline"] - y0
    ink = K.to565(np.array([[L["pad_ink"]]]))[0, 0].astype(float)
    dim = K.to565(np.array([[L["muted_ink"]]]))[0, 0].astype(float)
    imgs, lay = [], []

    def pad_img(code, text, colour):
        x0, x1 = PADS[code]
        w = x1 - x0 + 1
        p = scr[y0:y1 + 1, x0:x1 + 1].astype(np.int32)
        bg = K.rebuild(clear_tab(p, hdr), band, (w // 5, w - w // 5))
        a = K.alpha(text, font, w, H, w / 2, base)
        a[:band.start] = 0
        a[band.stop:] = 0
        return K.compose(bg.astype(float), a, colour), w

    def add(tag, img, w, h):
        imgs.append((tag, img))
        lay.append((tag, w, h))

    for i, n in enumerate(NAMES):
        img, w = pad_img(i + 1, n, ink)
        add("ON%d" % i, img, w, H)
        img, w = pad_img(i + 1, n, dim)
        add("MU%d" % i, img, w, H)
    img, w = pad_img(5, "ALL ON", ink)
    add("ALL", img, w, H)
    img, w = pad_img(6, "BACK", ink)
    add("BACK", img, w, H)
    tx0, tx1 = L["title_x"]
    ty0, ty1 = L["title_y"]
    tw, th = tx1 - tx0 + 1, ty1 - ty0 + 1
    for tag, col in (("TITLE", L["label_ink"]), ("ALERT", L["alert_ink"])):
        a = K.alpha("STEMS", K.font_for(L["cap_label"]), tw, th, tw / 2, L["baseline_label"] - ty0)
        add(tag, K.compose(np.zeros((th, tw, 3)), a, K.to565(np.array([[col]]))[0, 0].astype(float)), tw, th)

    os.makedirs(OUT, exist_ok=True)
    blob, offs = bytearray(), {}
    for tag, img in imgs:
        offs[tag] = len(blob)
        blob += K.pack(img)
        blob += bytes(-len(blob) % 4)
    open(os.path.join(OUT, "stemsui_img.bin"), "wb").write(blob)
    with open(os.path.join(OUT, "stemsui_layout.h"), "w") as f:
        f.write("/* generated by mk1/stemsui_assets.py */\n")
        for tag, w, h in lay:
            f.write("#define IMG_%s_OFF %du\n#define IMG_%s_W %d\n#define IMG_%s_H %d\n" % (tag, offs[tag], tag, w, tag, h))
    d = dict(imgs)
    row = scr[y0:y1 + 1, :640].astype(np.int32).copy()
    for code, tag in ((1, "ON0"), (2, "MU1"), (3, "ON2"), (4, "MU3"), (5, "ALL"), (6, "BACK")):
        x0, x1 = PADS[code]
        row[:, x0:x1 + 1] = d[tag]
    row[ty0 - y0:ty1 - y0 + 1, tx0:tx1 + 1] = d["TITLE"]
    stock = scr[y0:y1 + 1, :640].astype(np.int32)
    pv = np.vstack([K.rgb8(stock), np.zeros((4, 640, 3), np.uint8), K.rgb8(row)])
    Image.fromarray(pv).resize((1280, pv.shape[0] * 2), Image.NEAREST).save(os.path.join(OUT, "preview.png"))
    print("stemsui_img.bin %d B (%d images), sha256 %s" % (len(blob), len(imgs), hashlib.sha256(blob).hexdigest()))
    return bytes(blob), offs


if __name__ == "__main__":
    if sys.argv[1:] == ["build"]:
        build()
    else:
        print(__doc__)
